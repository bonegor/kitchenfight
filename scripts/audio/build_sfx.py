class Src:
    cache = os.path.join(tempfile.gettempdir(), 'kf-sfx-build-cache')
    _audio: dict = {}

    @staticmethod
    def path(ref: str) -> str:
        kind, rel = ref.split(':', 1)
        s = SOURCES[kind]
        if s.kind == 'dir':
            if kind == 'ocu':
                return os.path.join(s.loc, rel + '.ogg')
            if kind == 'kit':
                for d in sorted(os.listdir(s.loc)):
                    p = os.path.join(s.loc, d, rel + '.wav')
                    if os.path.exists(p):
                        return p
                raise FileNotFoundError(ref)
            return os.path.join(s.loc, rel)
        # blobless git clone: materialise the blob into the cache
        os.makedirs(Src.cache, exist_ok=True)
        h = hashlib.sha1(ref.encode()).hexdigest()[:20]
        out = os.path.join(Src.cache, h + os.path.splitext(rel)[1])
        if not os.path.exists(out):
            data = subprocess.run(['git', '-C', s.loc, 'show', 'HEAD:' + rel], capture_output=True, check=True).stdout
            tmp = out + '.part'
            with open(tmp, 'wb') as f:
                f.write(data)
            os.replace(tmp, out)
        return out

    @staticmethod
    def rel_path(ref: str) -> str:
        """human-readable path of the source file inside its collection"""
        kind, rel = ref.split(':', 1)
        if kind == 'ocu':
            return 'corpora/oculus-audio-pack/ogg/' + rel + '.ogg'
        if kind == 'kit':
            p = Src.path(ref)
            return 'sounds/' + os.path.basename(os.path.dirname(p)) + '/' + rel + '.wav'
        return rel

    @staticmethod
    def load(ref: str) -> np.ndarray:
        """source as float64 [n, 2] at 48 kHz (mono sources duplicated)"""
        if ref in Src._audio:
            return Src._audio[ref]
        p = Src.path(ref)
        raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', p, '-af', 'aresample=resampler=soxr:precision=28', '-ar', str(SR),
                              '-ac', '2', '-f', 'f32le', '-'], capture_output=True, check=True).stdout
        x = np.frombuffer(raw, dtype=np.float32).astype(np.float64).reshape(-1, 2)
        Src._audio[ref] = x
        return x


class Synth:
    """The synthesized sound effects (the loudness reference and the synth layers), rendered by the game's own code."""
    _dir: str | None = None
    _idx: dict = {}

    @staticmethod
    def dir() -> str:
        if Synth._dir is None:
            h = hashlib.sha1()
            for p in ('src/audio/sfx.ts', 'src/audio/dsp.ts', 'scripts/audio/sfx_synth_render.mjs'):
                with open(os.path.join(REPO, p), 'rb') as f:
                    h.update(f.read())
            d = os.path.join(Src.cache, 'synth-' + h.hexdigest()[:16])
            if not os.path.exists(os.path.join(d, 'index.json')):
                subprocess.run(['node', SYNTH_RENDER, d, str(SR)], check=True, cwd=REPO, stdout=subprocess.DEVNULL)
            with open(os.path.join(d, 'index.json')) as f:
                Synth._idx = json.load(f)
            Synth._dir = d
        return Synth._dir

    @staticmethod
    def variants(sid: str) -> int:
        Synth.dir()
        return int(Synth._idx['ids'][sid]['variants'])

    @staticmethod
    def pcm(sid: str, v: int) -> np.ndarray:
        d = Synth.dir()
        ch = int(Synth._idx['ids'][sid]['ch'])
        x = np.fromfile(os.path.join(d, f'{sid}.{v}.f32'), dtype=np.float32).astype(np.float64)
        return x.reshape(-1, ch)


