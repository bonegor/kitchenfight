def render_layer(ly: Layer, stereo: bool) -> np.ndarray:
    x = Src.load(ly.src)
    if ly.t0 is None:
        a = onset_of(x)
    else:
        a = int(round(ly.t0 * SR))
    if ly.peak_at is not None:
        # transient alignment for layering: put the attack's loudest millisecond at `peak_at`
        k = max(1, int(0.001 * SR))
        seg = (x[a:a + int(0.12 * SR)] ** 2).mean(axis=1)
        e = np.convolve(seg, np.ones(k) / k, mode='same')
        a = max(0, a + int(np.argmax(e)) - int(ly.peak_at * SR))
    b = len(x) if ly.dur is None else min(len(x), a + int(round(ly.dur * SR)))
    y = np.array(x[a:b], dtype=np.float64)
    if ly.width != 1.0:
        mid = y.mean(axis=1, keepdims=True)
        y = mid + (y - mid) * ly.width
    if not stereo:
        y = y.mean(axis=1, keepdims=True)
    elif ly.pan:
        # constant-power pan of the (mono-summed) layer
        th = (ly.pan + 1) * math.pi / 4
        m = y.mean(axis=1)
        y = np.stack([m * math.cos(th) * math.sqrt(2), m * math.sin(th) * math.sqrt(2)], axis=1)
    if ly.rev:
        y = y[::-1].copy()
    fi = ly.fi if ly.fi is not None else (0.0005 if ly.t0 is None else 0.003)
    y = fade(y, fi, ly.fo)
    rate = ly.rate * 2 ** (ly.semis / 12)
    if ly.note is not None:
        rate *= mtof(ly.note) / f0_of(ly.src, ly.f0, ly.expect)
    y = resample(y, rate)
    if ly.hp:
        y = butter(y, 'highpass', ly.hp, 2)
    if ly.hp4:
        y = butter(y, 'highpass', ly.hp4, 4)
    if ly.lp:
        y = butter(y, 'lowpass', ly.lp, 2)
    if ly.lp4:
        y = butter(y, 'lowpass', ly.lp4, 4)
    for e in ly.eq:
        y = biquad(y, e[0], e[1], e[2], e[3] if len(e) > 3 else 0.7)
    if ly.flatten:
        y = flatten_env(y, ly.flatten, ly.flat_max)
    n = len(y)
    if ly.tau:
        t = np.arange(n) / SR
        y *= np.where(t < ly.tau_at, 1.0, np.exp(-(t - ly.tau_at) / ly.tau))[:, None]
    if ly.env:
        y *= env_db(n, ly.env)[:, None]
    if ly.norm == 'peak':
        ref = np.abs(y).max()
    elif ly.norm == 'k':
        ref = 10 ** ((lk_win(kpow(y), 0.1) + 0.691) / 20) if len(y) else 0.0
    else:
        _, lo, hi = ly.norm
        ref = 10 ** (band_level(y, lo, hi) / 20)
    if ref > 0:
        y *= 10 ** (ly.gain / 20) / ref
    return y


def render_variant(v: Variant, stereo: bool, lead_db: float | None = None, post_eq: tuple = (), parts_out: list | None = None) -> np.ndarray:
    parts = [(int(round(ly.at * SR)), render_layer(ly, stereo), ly) for ly in v.layers]
    if parts_out is not None:
        parts_out.extend(parts)
    n = max(o + len(p) for o, p, _ in parts)
    ch = 2 if stereo else 1
    out = np.zeros((n, ch))
    for o, p, _ in parts:
        out[o:o + len(p)] += p
    out = butter(out, 'highpass', 20, 2)  # DC / subsonic
    for e in post_eq:
        out = biquad(out, e[0], e[1], e[2], e[3] if len(e) > 3 else 0.7)
    if v.max_len:
        out = fade(out[:int(v.max_len * SR)], 0, v.end_fade)
    # trim: lead to the first 0.5 ms window above TRIM_LEAD_DB (re the loudest; robust against stray clicks) or, with
    # lead_db, to the first sample above lead_db re the peak; minus the pre-roll. Tail after the last sample above
    # v.tail_db (re peak)
    m = np.abs(out).max(axis=1)
    pk = m.max()
    if lead_db is None:
        k = max(1, int(0.0005 * SR))
        e = np.sqrt(np.convolve((out ** 2).mean(axis=1), np.ones(k) / k, mode='same'))
        i0 = int(np.argmax(e > e.max() * 10 ** (TRIM_LEAD_DB / 20)))
    else:
        i0 = int(np.argmax(m > pk * 10 ** (lead_db / 20)))
    s = max(0, i0 - int(PREROLL * SR))
    idx = np.nonzero(m > pk * 10 ** (v.tail_db / 20))[0]
    e = min(len(out), int(idx[-1]) + 1 + int(0.005 * SR))
    out = out[s:e].copy()
    out = fade(out, PREROLL if s > 0 else 0.0, v.end_fade)
    out *= 10 ** (PEAK_DBFS / 20) / np.abs(out).max()
    return out


def kit_share(parts: list) -> float:
    """K-weighted energy share of the SFX Kit (code-synthesised) layers in a variant"""
    if not any(ly.src.startswith('kit:') for _, _, ly in parts):
        return 0.0
    n = max(o + len(p) for o, p, _ in parts)
    ch = parts[0][1].shape[1]
    kit, real = np.zeros((n, ch)), np.zeros((n, ch))
    for o, p, ly in parts:
        (kit if ly.src.startswith('kit:') else real)[o:o + len(p)] += p
    ek, er = float(kpow(kit).sum()), float(kpow(real).sum())
    return ek / max(ek + er, 1e-20)


TILT_EQ = (('low', 300), ('high', 3000), ('high', 8000))


def match_tilts(d: Design) -> list:
    """per-variant shelving EQ (300 Hz, 3 kHz, 8 kHz) that brings each variant's spectral balance (see tilt) to the
    id's mean, so round-robins differ in detail but not in timbre (bands with no content, < -30 dB re the mids in
    every variant, are left alone)"""
    base = np.array([tilt(render_variant(v, d.stereo, d.lead_db)) for v in d.variants])
    target = base.mean(axis=0)
    active = base.max(axis=0) > -30
    out = []
    for v, b0 in zip(d.variants, base):
        g = np.zeros(3)
        cur = b0.copy()
        for _ in range(5):
            g = np.where(active, np.clip(g + 0.9 * (target - cur), -9, 9), 0.0)
            eq = tuple((k, f, float(x)) for (k, f), x in zip(TILT_EQ, g) if x)
            cur = np.array(tilt(render_variant(v, d.stereo, d.lead_db, eq)))
            if np.abs(np.where(active, cur - target, 0)).max() < 0.4:
                break
        out.append(tuple((k, f, round(float(x), 2)) for (k, f), x in zip(TILT_EQ, g) if x))
    return out


def encode(y: np.ndarray, path: str) -> None:
    ch = y.shape[1]
    raw = y.astype(np.float32).tobytes()
    cmd = ['ffmpeg', '-v', 'error', '-y', '-f', 'f32le', '-ar', str(SR), '-ac', str(ch), '-i', '-',
           '-c:a', 'libmp3lame', '-q:a', str(LAME_Q), '-id3v2_version', '0', '-write_id3v1', '0', '-map_metadata', '-1']
    if ch == 2:
        cmd += ['-joint_stereo', '1']
    subprocess.run(cmd + [path], input=raw, check=True)


def decode(path: str, ch: int) -> np.ndarray:
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-f', 'f32le', '-ac', str(ch), '-ar', str(SR), '-'],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.float32).astype(np.float64).reshape(-1, ch)


def measure(y: np.ndarray) -> dict:
    m = np.abs(y).max(axis=1)
    pk = float(m.max())
    on = int(np.argmax(m > pk * 10 ** (-40 / 20)))
    # attack anchors for runtime alignment (sfxsamples.ts): first sample above -6 / -12 / -20 dB re peak
    anchors = [int(np.argmax(m > pk * 10 ** (d / 20))) for d in (-6, -12, -20)]
    act = y[on:]
    rms = math.sqrt(float((act ** 2).mean()))
    return dict(dur=round(len(y) / SR, 4), peak=round(db(pk), 2), tp=round(db(true_peak(y)), 2),
                rms=round(db(rms), 2), on=round(on / SR * 1000, 2), a20=round(anchors[2] / SR * 1000, 2), anchors=anchors,
                clip=int((np.abs(y) >= 1.0).sum()))


def mix_played(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """sum two buffers as the engine plays them (both up-mixed to stereo, starting together)"""
    a, b = played(a), played(b)
    n = max(len(a), len(b))
    out = np.zeros((n, 2))
    out[:len(a)] += a
    out[:len(b)] += b
    return out


def synth_refs(sid: str) -> dict:
    """loudness of the synthesized version of an id (power mean over its variants)"""
    ls = [loudness(Synth.pcm(sid, v)) for v in range(Synth.variants(sid))]
    return {k: 10 * math.log10(np.mean([10 ** (x[k] / 10) for x in ls])) for k in METRICS}


def solve_gain(dec: np.ndarray, refs: dict, lift: float, syn: tuple | None) -> tuple:
    """runtime gain (dB) of one decoded variant: the midpoint of the gains matching LK100, LK400 and the integrated
    loudness of the synthesized version (+ lift). With a synth layer (pcm, dB), the actual mix is matched."""
    target = {k: refs[k] + lift for k in METRICS}

    def metrics(g: float) -> dict:
        y = dec * 10 ** (g / 20)
        if syn is not None:
            y = mix_played(y, syn[0] * 10 ** (syn[1] / 20))
        return loudness(y)

    if syn is None:
        m0 = metrics(0.0)
        req = {k: target[k] - m0[k] for k in METRICS}
    else:
        req = {}
        for k in METRICS:
            lo, hi = -60.0, 30.0
            if metrics(lo)[k] > target[k]:
                req[k] = lo  # the synth layer alone is already louder: the recording adds as little as possible
                continue
            for _ in range(40):
                mid = (lo + hi) / 2
                if metrics(mid)[k] < target[k]:
                    lo = mid
                else:
                    hi = mid
            req[k] = (lo + hi) / 2
    g = (min(req.values()) + max(req.values())) / 2
    m = metrics(g)
    return g, {k: m[k] - target[k] for k in METRICS}, max(req.values()) - min(req.values())


def similarity(a: np.ndarray, b: np.ndarray, max_lag: float = 0.005) -> float:
    """normalised cross-correlation of two variants (mono sums), best alignment within +-max_lag"""
    a, b = a.mean(axis=1), b.mean(axis=1)
    n = 1 << int(math.ceil(math.log2(len(a) + len(b))))
    c = np.fft.irfft(np.fft.rfft(a, n) * np.conj(np.fft.rfft(b, n)), n)
    k = int(max_lag * SR)
    best = max(np.abs(c[:k + 1]).max(), np.abs(c[-k:]).max())
    return float(best / math.sqrt(float((a ** 2).sum() * (b ** 2).sum()) + 1e-20))


def manifest_json(m: dict) -> str:
    """compact, diff-friendly JSON: one line per asset / id"""
    def block(d: dict) -> str:
        return '{\n' + ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v, separators=(",", ":"))}' for k, v in d.items()) + '\n }'
    return ('{\n "version": ' + json.dumps(m['version']) + ',\n "sr": ' + json.dumps(m['sr']) +
            ',\n "credits": ' + json.dumps(m['credits'], indent=None, ensure_ascii=False) +
            ',\n "assets": ' + block(m['assets']) + ',\n "ids": ' + block(m['ids']) + '\n}\n')


def credit_lines(design: dict) -> list:
    """attribution lines for the game's Credits screen (only collections that are used)"""
    used = {ly.src.split(':', 1)[0] for d in design.values() for v in d.variants for ly in v.layers}
    lines = ['Sound effects: recordings (and a few synthesized layers) from the collections below, edited and mixed for this game.']
    lines += [s.credit for k, s in SOURCES.items() if k in used]
    return lines


def build(only: set | None, jobs: int) -> None:
    design = build_design()
    os.makedirs(OUT_DIR, exist_ok=True)
    man_path = os.path.join(OUT_DIR, 'manifest.json')
    old = json.load(open(man_path)) if (only and os.path.exists(man_path)) else None

    tasks = []
    for sid, d in design.items():
        if only and sid not in only:
            continue
        for k, v in enumerate(d.variants):
            name = sid if len(d.variants) == 1 else f'{sid}_{k + 1}'
            tasks.append((sid, d, k, name, v))

    # load all sources first (cached), then render in parallel threads (numpy/scipy release the GIL)
    for _, _, _, _, v in tasks:
        for ly in v.layers:
            Src.load(ly.src)
            if ly.note is not None:
                f0_of(ly.src, ly.f0, ly.expect)
    refs = {sid: synth_refs(sid) for sid in {t[0] for t in tasks}}
    eqs = {}
    for sid, d in design.items():
        if d.match and (not only or sid in only):
            eqs[sid] = match_tilts(d)

    def work(t):
        sid, d, k, name, v = t
        parts: list = []
        y = render_variant(v, d.stereo, d.lead_db, eqs[sid][k] if sid in eqs else (), parts)
        path = os.path.join(OUT_DIR, name + '.mp3')
        encode(y, path)
        dec = decode(path, y.shape[1])
        mm = measure(dec)
        mm['src_len'] = len(y)
        mm['dec_len'] = len(dec)
        mm['bytes'] = os.path.getsize(path)
        mm['kit'] = round(kit_share(parts), 3)
        mm['tilt'] = [round(v_, 2) for v_ in tilt(dec)]
        # MP3 fidelity: error of the decoded file vs. the rendered PCM (aligned by ffmpeg's gapless decoding)
        n = min(len(y), len(dec))
        err = dec[:n] - y[:n]
        mm['snr'] = round(db(math.sqrt(float((y[:n] ** 2).mean()))) - db(math.sqrt(float((err ** 2).mean())) + 1e-12), 1)
        syn = (Synth.pcm(sid, k % Synth.variants(sid)), d.synth) if d.synth is not None else None
        lift = d.lift + (d.vgain[k] if d.vgain else 0.0)
        g, dev, spread = solve_gain(dec, refs[sid], lift, syn)
        mm['gain'] = round(g, 2)
        mm['dev'] = {k_: round(v_, 2) for k_, v_ in dev.items()}
        mm['spread'] = round(spread, 2)
        mm['lk'] = round(loudness(dec)['lk100'], 2)
        return sid, name, y.shape[1], mm

    with ThreadPoolExecutor(max_workers=jobs) as ex:
        results = list(ex.map(work, tasks))

    assets = dict(old['assets']) if old else {}
    ids = dict(old['ids']) if old else {}
    meas = {}
    for sid, name, ch, mm in results:
        assets[name] = {'ch': ch, 'dur': mm['dur'], 'lk': mm['lk'], 'a': mm['anchors']}
        meas[name] = mm
    for sid, d in design.items():
        if only and sid not in only:
            continue
        names = [sid if len(d.variants) == 1 else f'{sid}_{k + 1}' for k in range(len(d.variants))]
        ids[sid] = {'v': names, 'g': [meas[n]['gain'] for n in names], 'pv': d.pv, 'vv': d.vv, 'syn': d.synth}
    # drop stale files
    keep = {n + '.mp3' for n in assets}
    for f in os.listdir(OUT_DIR):
        if f.endswith('.mp3') and f not in keep:
            os.remove(os.path.join(OUT_DIR, f))
    order = list(design.keys())
    manifest = {'version': 1, 'sr': SR, 'credits': credit_lines(design), 'assets': {k: assets[k] for k in sorted(assets)},
                'ids': {k: ids[k] for k in order if k in ids}}
    with open(man_path, 'w') as f:
        f.write(manifest_json(manifest))
    total = sum(os.path.getsize(os.path.join(OUT_DIR, n + '.mp3')) for n in assets)
    print(f'{len(results)} variants rendered; {len(assets)} assets, {total / 1024:.1f} KiB of MP3')
    print(f"  {'asset':22s} ch  dur     gain   dLK100 dLK400  dINT  spread  a20ms  kit%  tilt lo/hi/air    snr  bytes")
    warn = []
    for sid, name, ch, mm in sorted(results, key=lambda r: (order.index(r[0]), r[1])):
        dv = mm['dev']
        print(f"  {name:22s} {ch}  {mm['dur']:.3f}  {mm['gain']:6.2f}  {dv['lk100']:+5.1f}  {dv['lk400']:+5.1f}  {dv['lki']:+5.1f}  "
              f"{mm['spread']:5.1f}  {mm['a20']:5.1f}  {mm['kit'] * 100:4.0f}  {mm['tilt'][0]:+5.1f}/{mm['tilt'][1]:+5.1f}/{mm['tilt'][2]:+5.1f}  {mm['snr']:4.1f}  {mm['bytes']}")
        if mm['spread'] > MAX_SPREAD:
            warn.append(f'{name}: LK100/LK400/integrated matches disagree by {mm["spread"]:.1f} dB')
    # round-robins must really differ (a near-copy halves the variety): whole sound, and its attack (first 25 ms, where
    # variants of one tuned note - pickup_xp - differ; their sustained fundamental is the same by design)
    sims = {}
    for sid, d in design.items():
        if (only and sid not in only) or len(d.variants) < 2:
            continue
        names = ids[sid]['v']
        decs = [decode(os.path.join(OUT_DIR, n + '.mp3'), assets[n]['ch']) for n in names]
        pairs = [(i, j) for i in range(len(decs)) for j in range(i + 1, len(decs))]
        whole = max(similarity(decs[i], decs[j]) for i, j in pairs)
        attack = max(similarity(decs[i][:int(0.025 * SR)], decs[j][:int(0.025 * SR)]) for i, j in pairs)
        sims[sid] = (whole, attack)
        if (attack > 0.9 or whole > 0.9) and not d.key:  # variants of one tuned note (pickup_xp) are alike by design
            warn.append(f'{sid}: two variants are near-copies (cross-correlation {whole:.2f}, attack {attack:.2f})')
    print('  variant similarity (max normalised cross-correlation, whole / attack): ' + ', '.join(f'{k} {w:.2f}/{a:.2f}' for k, (w, a) in sims.items()))
    for w in warn:
        print('  WARNING', w)
    for sid, v in sims.items():
        for n in ids[sid]['v']:
            meas[n]['sim'] = [round(v[0], 2), round(v[1], 2)]
    with open(os.path.join(Src.cache, 'last_measure.json'), 'w') as f:
        json.dump(meas, f, indent=1)
    if not only:
        write_credits(design, manifest, meas, {sid: refs[sid] for sid in refs})


