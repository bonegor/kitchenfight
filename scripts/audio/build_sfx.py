"""
KITCHEN FIGHT - Audio 2.0, recorded sound effects.

Builds every recorded SFX asset from the local source clones (see SOURCES below), reproducibly:

    /home/user/.venv-audio/bin/python -I scripts/audio/build_sfx.py [--cache DIR] [--only id,id] [--jobs N]

For each of the game's SFX ids (src/audio/audio.ts) the DESIGN table lists one or more *variants*. Every variant
is a mix of *layers*: a slice of a source recording (trimmed, re-pitched by resampling, filtered, enveloped,
placed in time, panned). The rendered variant is trimmed (leading/trailing near-silence), faded, peak-normalised
to -1.5 dBFS and encoded as MP3 (libmp3lame VBR, 48 kHz, mono unless the design needs stereo). The MP3 is then
decoded again and measured; the runtime gain of each variant is computed on the *decoded* audio.

Outputs (all generated, do not edit by hand):
    src/audio/assets/sfx/<asset>.mp3     the encoded variants
    src/audio/assets/sfx/manifest.json   per id: variants, runtime gain (dB), random pitch/gain ranges, synth layer;
                                         the attribution lines (`credits`, shown by the game's Credits screen)
    docs/credits/sfx.md                  every source file used, its license and the required attribution

Loudness. The reference is the game's original balance: the SYNTHESIZED version of each id (src/audio/sfx.ts),
rendered with the game's own code by scripts/audio/sfx_synth_render.mjs. Three K-weighted (ITU-R BS.1770) measures
are taken on the signal as played (mono up-mixed to both speakers): LK100 (loudest 100 ms: the attack), LK400
(loudest 400 ms: the body) and the gated integrated loudness of the whole sound. Each variant's runtime gain is the
midpoint of the three gains that would match each measure, so no measure deviates by more than half their spread;
designs are shaped until that spread is small (printed by the build, tabled in docs/credits/sfx.md). Ids with a synth
layer are matched as the actual mix (recording + synthesized layer). `lift` raises an id above the synthesized
balance on purpose (each one is explained in the design table).
"""
