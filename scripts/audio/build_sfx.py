def mtof(m: float) -> float:
    return 440.0 * 2 ** ((m - 69) / 12)


def db(x: float) -> float:
    return 20 * math.log10(max(x, 1e-12))


def kweight(x: np.ndarray) -> np.ndarray:
    b1 = [1.53512485958697, -2.69169618940638, 1.19839281085285]
    a1 = [1.0, -1.69065929318241, 0.73248077421585]
    b2 = [1.0, -2.0, 1.0]
    a2 = [1.0, -1.99004745483398, 0.99007225036621]
    return signal.lfilter(b2, a2, signal.lfilter(b1, a1, x, axis=0), axis=0)


def played(x: np.ndarray) -> np.ndarray:
    """[n, ch] -> [n, 2] as heard on stereo output (a mono buffer is up-mixed to both speakers)"""
    return np.repeat(x, 2, axis=1) if x.shape[1] == 1 else x


def kpow(x: np.ndarray) -> np.ndarray:
    """K-weighted power per sample, summed over the played channels (BS.1770)"""
    z = kweight(played(x))
    return (z ** 2).sum(axis=1)


def lk_win(p: np.ndarray, win: float) -> float:
    """loudest `win` window of a K-weighted power signal (LUFS scale)"""
    n = int(win * SR)
    if len(p) < n:
        p = np.concatenate([p, np.zeros(n - len(p))])
    c = np.concatenate([[0.0], np.cumsum(p)])
    hop = max(1, int(0.0025 * SR))
    m = (c[n::hop] - c[:-n:hop]) / n
    return -0.691 + 10 * math.log10(max(float(m.max()), 1e-15))


INT_PHASES = (0.0, 0.025, 0.05, 0.075)  # s: block-grid offsets averaged by lk_int


def lk_int(p: np.ndarray) -> float:
    """BS.1770-4 gated integrated loudness: 400 ms blocks with 75 % overlap, -70 LUFS absolute / -10 LU relative gates.
    The sound is padded with silence so that short sounds are measured like long ones; for a short sound the result
    moves by up to ~1 dB with the position of the 100 ms block grid, so it is averaged over four grid offsets
    (scripts/audio/sfx_measure.mjs does the same)."""
    n, hop = int(0.4 * SR), int(0.1 * SR)
    out = []
    for ph in INT_PHASES:
        q = np.concatenate([np.zeros(n + int(ph * SR)), p, np.zeros(n)])
        c = np.concatenate([[0.0], np.cumsum(q)])
        blocks = (c[n::hop] - c[:-n:hop]) / n
        lv = -0.691 + 10 * np.log10(np.maximum(blocks, 1e-15))
        g1 = blocks[lv > -70]
        if not len(g1):
            return -99.0
        rel = -0.691 + 10 * math.log10(g1.mean()) - 10
        g2 = g1[(-0.691 + 10 * np.log10(g1)) > rel]
        out.append(-0.691 + 10 * math.log10(g2.mean()))
    return float(np.mean(out))


METRICS = ('lk100', 'lk400', 'lki')


def loudness(x: np.ndarray) -> dict:
    p = kpow(x)
    return {'lk100': lk_win(p, 0.1), 'lk400': lk_win(p, 0.4), 'lki': lk_int(p)}


def true_peak(x: np.ndarray) -> float:
    y = signal.resample_poly(x, 4, 1, axis=0)
    return float(np.abs(y).max())


def butter(x: np.ndarray, kind: str, f, order: int = 2) -> np.ndarray:
    f = min(f, SR * 0.45) if not isinstance(f, (tuple, list)) else [min(v, SR * 0.45) for v in f]
    sos = signal.butter(order, f, btype=kind, fs=SR, output='sos')
    return signal.sosfilt(sos, x, axis=0)


def biquad(x: np.ndarray, kind: str, f: float, g: float, q: float = 0.7) -> np.ndarray:
    """RBJ cookbook peaking / low-shelf / high-shelf"""
    A = 10 ** (g / 40)
    w = 2 * math.pi * f / SR
    cw, sw = math.cos(w), math.sin(w)
    if kind == 'peak':
        al = sw / (2 * q)
        b = [1 + al * A, -2 * cw, 1 - al * A]
        a = [1 + al / A, -2 * cw, 1 - al / A]
    else:
        al = sw / 2 * math.sqrt(2)
        sq = 2 * math.sqrt(A) * al
        if kind == 'low':
            b = [A * ((A + 1) - (A - 1) * cw + sq), 2 * A * ((A - 1) - (A + 1) * cw), A * ((A + 1) - (A - 1) * cw - sq)]
            a = [(A + 1) + (A - 1) * cw + sq, -2 * ((A - 1) + (A + 1) * cw), (A + 1) + (A - 1) * cw - sq]
        else:
            b = [A * ((A + 1) + (A - 1) * cw + sq), -2 * A * ((A - 1) + (A + 1) * cw), A * ((A + 1) + (A - 1) * cw - sq)]
            a = [(A + 1) - (A - 1) * cw + sq, 2 * ((A - 1) - (A + 1) * cw), (A + 1) - (A - 1) * cw - sq]
    return signal.lfilter(b, a, x, axis=0)


def resample(x: np.ndarray, rate: float) -> np.ndarray:
    """play `rate` times faster (pitch up by rate, shorter)"""
    if abs(rate - 1) < 1e-6:
        return x
    fr = Fraction(rate).limit_denominator(480)
    return signal.resample_poly(x, fr.denominator, fr.numerator, axis=0, window=('kaiser', 8.0))


def onset_of(x: np.ndarray, thr_db: float = -20.0, backoff: float = 0.002) -> int:
    """attack of a recording: first 0.5 ms-RMS window above thr_db (re the loudest window), minus `backoff`
    (robust against the noise floor and lone spikes that precede soft hits)"""
    m = (x ** 2).mean(axis=1)
    k = max(1, int(0.0005 * SR))
    e = np.sqrt(np.convolve(m, np.ones(k) / k, mode='same'))
    pk = e.max()
    if pk <= 0:
        return 0
    i = int(np.argmax(e > pk * 10 ** (thr_db / 20)))
    return max(0, i - int(backoff * SR))


def f0_estimate(x: np.ndarray, how: str = 'acf', expect: float | None = None) -> float:
    """fundamental of a pitched one-shot: autocorrelation (plucked strings, brass) or strongest partial (mallets).
    With `expect` (Hz) the search is limited to +-8 % around it (no octave / overtone errors)."""
    m = x.mean(axis=1)
    on = int(np.argmax(np.abs(m) > np.abs(m).max() * 0.1))
    seg = m[on + int(0.04 * SR): on + int(0.34 * SR)]
    if how == 'peak':
        N = 1 << 17
        F = np.abs(np.fft.rfft(seg * np.hanning(len(seg)), N))
        f = np.fft.rfftfreq(N, 1 / SR)
        lo, hi = (expect / 1.08, expect * 1.08) if expect else (150, 9000)
        F[(f < lo) | (f > hi)] = 0
        i = int(np.argmax(F))
        y0, y1, y2 = (math.log(F[i + k] + 1e-12) for k in (-1, 0, 1))
        return (i + 0.5 * (y0 - y2) / (y0 - 2 * y1 + y2)) * SR / N
    seg = seg - seg.mean()
    n = len(seg)
    ac = np.fft.irfft(np.abs(np.fft.rfft(seg, 2 * n)) ** 2)[:n]
    ac /= ac[0] + 1e-12
    lo, hi = (int(SR / (expect * 1.08)), int(SR / (expect / 1.08)) + 1) if expect else (int(SR / 2500), int(SR / 60))
    s = ac[lo:hi]
    if expect:
        i = int(np.argmax(s))
    else:
        i = int(np.nonzero(s > 0.85 * s.max())[0][0])
        while i + 1 < len(s) and s[i + 1] > s[i]:
            i += 1
    lag = i + lo
    y0, y1, y2 = ac[lag - 1], ac[lag], ac[lag + 1]
    return SR / (lag + 0.5 * (y0 - y2) / (y0 - 2 * y1 + y2 + 1e-12))


_F0: dict = {}


def f0_of(ref: str, how: str, expect: float | None = None) -> float:
    key = f'{ref}|{how}|{expect}'
    if key not in _F0:
        _F0[key] = f0_estimate(Src.load(ref), how, mtof(expect) if expect is not None else None)
    return _F0[key]


def env_db(n: int, pts) -> np.ndarray:
    """piecewise-linear (in dB) envelope through (t, dB) points; holds the end values"""
    t = np.arange(n) / SR
    ts = [p[0] for p in pts]
    vs = [p[1] for p in pts]
    return 10 ** (np.interp(t, ts, vs) / 20)


def fade(x: np.ndarray, fi: float, fo: float) -> np.ndarray:
    n = len(x)
    if fi > 0:
        k = min(n, max(1, int(fi * SR)))
        x[:k] *= (0.5 - 0.5 * np.cos(np.pi * np.arange(k) / k))[:, None]
    if fo > 0:
        k = min(n, max(1, int(fo * SR)))
        x[n - k:] *= (0.5 + 0.5 * np.cos(np.pi * (np.arange(k) + 1) / k))[:, None]
    return x


def flatten_env(y: np.ndarray, win: float, max_boost: float = 18.0) -> np.ndarray:
    """level a sound's short-term K-weighted loudness: each `win` window is raised to the loudest one (at most by
    `max_boost` dB), with a smooth gain curve (used for the falling whistle, which naturally fades as it falls)"""
    p = kweight(y)
    p = (p ** 2).sum(axis=1)
    n = max(1, int(win * SR))
    e = np.convolve(p, np.ones(n) / n, mode='same')
    top = e.max()
    if top <= 0:
        return y
    gain_db = np.clip(10 * np.log10(top / np.maximum(e, top * 1e-6)), 0, max_boost)
    hop = max(1, n // 4)
    t = np.arange(0, len(y), hop)
    gs = signal.savgol_filter(gain_db[t], min(len(t) // 2 * 2 - 1, 9), 2) if len(t) >= 5 else gain_db[t]
    g = np.interp(np.arange(len(y)), t, np.clip(gs, 0, max_boost))
    return y * (10 ** (g / 20))[:, None]


def band_level(x: np.ndarray, lo: float, hi: float, win: float = 0.02) -> float:
    """loudest `win` RMS window (dB) of the signal band-passed to lo..hi Hz"""
    m = x.mean(axis=1)
    y = butter(m, 'bandpass', [lo, hi], 4)
    n = max(1, int(win * SR))
    e = np.convolve(y ** 2, np.ones(n) / n, mode='same')
    return 10 * math.log10(max(float(e.max()), 1e-20))


def tilt(x: np.ndarray) -> tuple:
    """spectral balance: energy below 300 Hz, at 3-8 kHz and above 8 kHz, each in dB re 300 Hz..3 kHz"""
    m = x.mean(axis=1)
    N = 1 << max(12, int(math.ceil(math.log2(len(m)))))
    F = np.abs(np.fft.rfft(m, N)) ** 2
    f = np.fft.rfftfreq(N, 1 / SR)
    lo, mid, hi, air = (F[(f >= a) & (f < b)].sum() + 1e-20 for a, b in ((30, 300), (300, 3000), (3000, 8000), (8000, 16000)))
    return 10 * math.log10(lo / mid), 10 * math.log10(hi / mid), 10 * math.log10(air / mid)


