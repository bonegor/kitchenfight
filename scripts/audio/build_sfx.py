@dataclass
class Layer:
    src: str
    t0: float | None = None       # start in the source (s); None = detected onset - 2 ms
    dur: float | None = None      # seconds of source used (before re-pitching); None = to the end
    at: float = 0.0               # placement in the variant (s)
    gain: float = 0.0             # dB: the layer's level after normalisation (see `norm`)
    norm: object = 'peak'         # 'peak': sample peak = gain dBFS; 'k': LK100 = gain LUFS;
                                  # ('band', lo, hi): loudest 20 ms RMS in lo..hi Hz = gain dB (e.g. a crack's 2-8 kHz)
    rate: float = 1.0             # resampling factor (>1 = higher and shorter)
    semis: float = 0.0            # extra transposition in semitones
    note: float | None = None     # tune to this MIDI note (f0 measured from the source)
    f0: str = 'acf'               # f0 estimator for `note`: 'acf' (harmonic) or 'peak' (mallets, bells)
    expect: float | None = None   # nominal MIDI pitch of the source (restricts the f0 search to +-8 %)
    hp: float | None = None       # high-pass (Hz, 2nd order) ...
    lp: float | None = None       # ... low-pass
    hp4: float | None = None      # steeper (4th order) high-pass ...
    lp4: float | None = None      # ... and low-pass
    eq: tuple = ()                # (('peak'|'low'|'high', f, dB[, q]), ...) - after re-pitching (output frequencies)
    fi: float | None = None       # fade-in (s, on the used slice); default 0.5 ms at a detected onset, 3 ms after an explicit t0
    fo: float = 0.01              # fade-out (s, at the end of the slice)
    tau: float | None = None      # extra exponential decay (time constant, s) ...
    tau_at: float = 0.0           # ... starting here (s after the layer start)
    env: tuple | None = None      # ((t, dB), ...) amplitude envelope over the layer
    flatten: float | None = None  # level the layer's short-term loudness (window in s), see flatten_env ...
    flat_max: float = 18.0        # ... raising quiet parts by at most this (dB)
    pan: float = 0.0              # -1..1 (stereo variants only)
    width: float = 1.0            # stereo sources: 0 = mono, 1 = as recorded
    rev: bool = False             # reversed
    peak_at: float | None = None  # align: start the slice so the loudest 1 ms within 120 ms of the onset lands here (s)
    pitched: bool = False         # tonal layer without `note` (bells, chimes, stings): checked by sfx_tuning_check.py ...
    keyref: bool = False          # ... a recorded piece of music that sets the id's key (its own partials are not checked)


def L(src: str, **kw) -> Layer:
    return Layer(src, **kw)


@dataclass
class Variant:
    layers: list
    tail_db: float = TRIM_TAIL_DB
    end_fade: float = 0.015       # fade at the very end after tail trimming (s)
    max_len: float | None = None  # hard cap (s), faded


def V(*layers: Layer, **kw) -> Variant:
    return Variant(list(layers), **kw)


@dataclass
class Design:
    variants: list
    lift: float = 0.0             # dB above the synthesized version's loudness (deliberate; see `why`)
    why: str = ''                 # reason for a lift
    pv: float = 0.03              # random playback-rate spread per play (+-)
    vv: float = 0.06              # random gain spread per play (+-)
    stereo: bool = False
    synth: float | None = None    # also play the synthesized version at this gain (dB re its own level)
    note: str = ''
    vgain: list = field(default_factory=list)  # optional per-variant offsets (dB)
    lead_db: float | None = None  # event-locked sounds: trim the lead to the first sample above this (dB re peak),
                                  # so the perceptual attack starts at once; None = TRIM_LEAD_DB on 0.5 ms RMS windows
    match: bool = False           # equalise the variants' spectral balance (tilt) to their mean
    key: str | None = None        # musical ids: tonic of the major key every tonal layer must fit (sfx_tuning_check.py)


