def write_credits(design: dict, manifest: dict, meas: dict, refs: dict) -> None:
    used: dict = {}
    for sid, d in design.items():
        for v in d.variants:
            for ly in v.layers:
                used.setdefault(ly.src, set()).add(sid)
    lines = ['# Sound effects: sources and credits', '',
             'Generated by `scripts/audio/build_sfx.py` (do not edit by hand). Every recorded sound effect in',
             '`src/audio/assets/sfx/` is mixed from the source files below (trimmed, re-pitched, filtered, layered,',
             'loudness-matched and encoded as MP3). Where an id lists a synth layer, the game also plays its original',
             'synthesized sound (`src/audio/sfx.ts`), which is also the fallback whenever the MP3s cannot be decoded.', '',
             '## Attribution (required: CC BY 4.0, CC Sampling Plus 1.0)', '',
             'The same lines are in `src/audio/assets/sfx/manifest.json` (`credits`) and exported by `src/audio/sfxsamples.ts`',
             'as `SFX_CREDITS`, for the in-game Credits screen and the README:', '']
    lines += ['> ' + c + '  ' for c in manifest['credits']]
    lines += ['', '| collection | license | used for |', '|---|---|---|']
    for k, s in SOURCES.items():
        ids = sorted({i for r, ss in used.items() if r.startswith(k + ':') for i in ss})
        if ids:
            lines.append(f'| {s.name} | [{s.license[0]}]({s.license[1]}) | {len(ids)} ids |')
    kit_note = SOURCES['kit'].note
    lines += ['', f'Note on SFX Kit: {kit_note}', '']
    lines += ['## Sound design map (id -> variants -> sources)', '',
              'Loudness: each recorded variant is matched to the synthesized version of its id (the original balance against',
              'the music) on three K-weighted measures of the sound as played: LK100 (loudest 100 ms, the attack), LK400',
              '(loudest 400 ms, the body) and the gated integrated loudness. The columns give the worst deviation over the',
              'variants (recorded minus synthesized, after the deliberate `lift`); `kit` is the K-weighted energy share of SFX Kit',
              '(code-synthesised) layers; `attack` is the first sample above -20 dB re the peak (ms); in brackets after the number',
              'of variants, the highest cross-correlation between two of them, whole sound / first 25 ms (1 = identical).', '',
              '| id | variants | lift (why) | synth layer | dLK100 / dLK400 / dINT (dB) | attack ms | kit % | design | sources |',
              '|---|---|---|---|---|---|---|---|---|']
    for sid, d in design.items():
        srcs = []
        for v in d.variants:
            for ly in v.layers:
                s = ly.src.split(':', 1)[1].split('/')[-1]
                if s not in srcs:
                    srcs.append(s)
        names = manifest['ids'][sid]['v']
        worst = {k: max((meas[n]['dev'][k] for n in names), key=abs) for k in METRICS}
        nv = f"{len(d.variants)} ({meas[names[0]]['sim'][0]:.2f} / {meas[names[0]]['sim'][1]:.2f})" if len(names) > 1 else '1'
        a20 = [meas[n]['a20'] for n in names]
        kit = max(meas[n]['kit'] for n in names)
        syn = f'{d.synth:+.0f} dB' if d.synth is not None else '-'
        lift = f'{d.lift:+.1f} ({d.why})' if d.lift else '-'
        lines.append(f"| `{sid}` | {nv} | {lift} | {syn} | {worst['lk100']:+.1f} / {worst['lk400']:+.1f} / {worst['lki']:+.1f} | "
                     f"{min(a20):.1f}..{max(a20):.1f} | {kit * 100:.0f} | {d.note} | " + ', '.join(f'`{s}`' for s in srcs) + ' |')
    lines += ['', '## Every source file used', '']
    for k, s in SOURCES.items():
        refs_ = sorted(r for r in used if r.startswith(k + ':'))
        if not refs_:
            continue
        lines += [f'### {s.name} ([{s.license[0]}]({s.license[1]}))', '', f'Local clone: `{s.loc}`', '']
        for r in refs_:
            lines.append(f'- `{Src.rel_path(r)}` - used by ' + ', '.join(f'`{x}`' for x in sorted(used[r])))
        lines.append('')
    os.makedirs(os.path.dirname(CREDITS), exist_ok=True)
    # keep the measurement section written by scripts/audio/sfx_measure.mjs --doc
    tail = ''
    if os.path.exists(CREDITS):
        old = open(CREDITS).read()
        if MEASURE_MARK in old:
            tail = '\n' + old[old.index(MEASURE_MARK):]
    with open(CREDITS, 'w') as f:
        f.write('\n'.join(lines).rstrip() + '\n' + tail)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--cache', default=Src.cache, help='cache directory for blobs fetched from the blobless git clones')
    ap.add_argument('--only', default='', help='comma-separated ids to rebuild (keeps the others in the manifest)')
    ap.add_argument('--jobs', type=int, default=4)
    ap.add_argument('--q', type=int, default=LAME_Q, help='libmp3lame VBR quality (0 = best, 9 = smallest)')
    a = ap.parse_args()
    Src.cache = a.cache
    globals()['LAME_Q'] = a.q
    only = {s for s in a.only.split(',') if s} or None
    build(only, a.jobs)


if __name__ == '__main__':
    main()
